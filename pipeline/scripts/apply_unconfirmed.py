"""Move items Wowhead Forever marks Unconfirmed into the Unconfirmed source.

The item list on Wowhead Forever carries an `envChange` record per item:
new, updated, unchanged, or unconfirmed. An unconfirmed page shows the
"Unconfirmed" label, and seasonal leftovers also say "This item may not be
in WoW: Forever". `env_change.json` is that list, crawled from
https://www.wowhead.com/forever/items?filter=195;1;0 in item-level slices.

An unconfirmed item keeps its stored instructions, zone, npc, and pins, so
the hunt still says where it would come from. Its sourceType becomes
`unsourced`, which the log labels Unconfirmed and hides until the player
turns it on. The old sourceType is kept in `unconfirmedFrom`. When a later
crawl no longer marks the item unconfirmed, the old sourceType comes back.

The rows stay scored, so rank numbers do not move when Unconfirmed is
turned on or off. Writes sources.json, patches the generated class Lua in
place, and writes GearQuest/_generated/Data.Unconfirmed.generated.lua.

The same rows carry Wowhead's item set id. An item whose stored itemset is
0 takes it from the list (Stormcloth, the Forever Soulforge and Five
Thunders copies), so payload.py labels it (Set piece).
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gq_paths import DATA  # noqa: E402
import reclass_drop_sources as rd  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
ENV = Path(DATA) / "forever_wowhead" / "env_change.json"
SOURCES = Path(DATA) / "sources.json"
ITEMS = Path(DATA) / "items.json"
LUA = ROOT / "GearQuest" / "_generated" / "Data.Unconfirmed.generated.lua"


def main() -> None:
    env = json.loads(ENV.read_text(encoding="utf-8"))["items"]
    sources = json.loads(SOURCES.read_text(encoding="utf-8"))
    unconfirmed = sorted(
        int(k) for k, row in env.items() if (row.get("envChange") or {}).get("status") == "unconfirmed"
    )
    flagged = set(unconfirmed)
    moved = restored = 0
    patched = {}
    for key, src in sources.items():
        if not isinstance(src, dict):
            continue
        iid = int(key)
        status = (env.get(key, {}).get("envChange") or {}).get("status")
        if iid in flagged:
            if src.get("sourceType") != "unsourced":
                src["unconfirmedFrom"] = src.get("sourceType")
                src["sourceType"] = "unsourced"
                moved += 1
                patched[key] = src
        elif src.get("unconfirmedFrom") and status in ("new", "updated", "unchanged"):
            src["sourceType"] = src.pop("unconfirmedFrom")
            restored += 1
            patched[key] = src
    tmp = SOURCES.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(sources, ensure_ascii=True, separators=(",", ":")), encoding="utf-8")
    tmp.replace(SOURCES)

    items = json.loads(ITEMS.read_text(encoding="utf-8"))
    sets = 0
    for key, row in env.items():
        it = items.get(key)
        if it is not None and not it.get("itemset") and row.get("itemset"):
            it["itemset"] = int(row["itemset"])
            sets += 1
    if sets:
        tmp_items = ITEMS.with_suffix(".json.tmp")
        tmp_items.write_text(json.dumps(items, separators=(",", ":"), ensure_ascii=True), encoding="utf-8")
        tmp_items.replace(ITEMS)
    print(f"itemset filled {sets}")
    rd.patch_lua(
        {
            k: {
                "sourceType": v.get("sourceType"),
                "instructions": v.get("instructions"),
                "zone": v.get("zone"),
                "npc": v.get("npc"),
            }
            for k, v in patched.items()
        }
    )
    lines = [
        "-- AUTO-GENERATED by pipeline/scripts/apply_unconfirmed.py — do not edit.",
        "-- Items Wowhead Forever marks Unconfirmed (envChange status), from env_change.json.",
        "local _, GQ = ...",
        "GQ.Data = GQ.Data or {}",
        "GQ.Data.unconfirmed = {}",
        "local ids = {",
    ]
    for i in range(0, len(unconfirmed), 12):
        lines.append("    " + ", ".join(str(n) for n in unconfirmed[i : i + 12]) + ",")
    lines += ["}", "for i = 1, #ids do", "    GQ.Data.unconfirmed[ids[i]] = true", "end", ""]
    LUA.write_bytes("\n".join(lines).encode("utf-8"))
    print(f"unconfirmed {len(unconfirmed)} moved {moved} restored {restored} -> {LUA}")


if __name__ == "__main__":
    main()
