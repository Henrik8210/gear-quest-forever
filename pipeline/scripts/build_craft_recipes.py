"""Write CraftRecipes.generated.lua: the recipe item that teaches each craft.

Source: the Wowhead Forever profession lists in
pipeline/data/forever_wowhead/professions/*.json. Each recipe spell names the
items that teach it (`src.items`) and the list carries those items' name,
icon, and quality. A craft taught only by a trainer, or known from the start,
has no recipe item and gets no row.

When a spell lists more than one item, the one whose name is the crafted
piece wins (Plans: Stronger-hold Gauntlets is not Stronghold Gauntlets), then
the lowest id, so a Season of Discovery copy does not replace the original.
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PROFESSIONS = ROOT / "pipeline" / "data" / "forever_wowhead" / "professions"
GEN = ROOT / "GearQuest" / "_generated"
CRAFT_SKILLS = GEN / "CraftSkills.generated.lua"
OUT = GEN / "CraftRecipes.generated.lua"

ROW = re.compile(r'^GQ\.CraftSkills\[(\d+)\] = \{ profession = "(?:\\.|[^"\\])*", skill = \d+, spellId = (\d+)', re.M)


def lua_string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    by_spell: dict[int, dict] = {}
    names: dict[int, list] = {}
    for path in sorted(PROFESSIONS.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        for key, value in (data.get("items") or {}).items():
            names[int(key)] = value
        for recipe in data.get("recipes") or []:
            by_spell[int(recipe["s"])] = recipe

    rows = []
    no_item = 0
    for item_id, spell_id in ROW.findall(CRAFT_SKILLS.read_text(encoding="utf-8")):
        recipe = by_spell.get(int(spell_id))
        candidates = [int(x) for x in ((recipe or {}).get("src") or {}).get("items") or [] if int(x) in names]
        if not candidates:
            no_item += 1
            continue
        made = (recipe.get("n") or "").strip().lower()

        def same_piece(rid: int) -> bool:
            name = str(names[rid][0])
            return name.split(": ", 1)[-1].strip().lower() == made

        matching = [rid for rid in candidates if same_piece(rid)]
        pick = min(matching or candidates)
        name, icon, quality = names[pick][0], names[pick][1], names[pick][2]
        rows.append((int(item_id), pick, str(name), int(icon or 0), int(quality or 1)))

    rows.sort()
    lines = [
        "-- AUTO-GENERATED by pipeline/scripts/build_craft_recipes.py — do not edit.",
        "-- Source: Wowhead Forever profession lists (the item that teaches each recipe).",
        "-- { recipe item id, English name, icon file id, quality }",
        "",
        "local _, GQ = ...",
        "GQ.CraftRecipes = GQ.CraftRecipes or {}",
    ]
    for item_id, recipe_id, name, icon, quality in rows:
        lines.append("GQ.CraftRecipes[%d] = { %d, %s, %d, %d }" % (item_id, recipe_id, lua_string(name), icon, quality))
    tmp = OUT.with_name(OUT.name + ".tmp")
    tmp.write_text("\n".join(lines) + "\n", encoding="utf-8")
    os.replace(tmp, OUT)
    print("wrote %s: %d crafts with a recipe item, %d taught by a trainer or known" % (OUT.name, len(rows), no_item))


if __name__ == "__main__":
    main()
