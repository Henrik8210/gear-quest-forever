#!/usr/bin/env node
/**
 * Emit GearQuest/_generated/StatWeights.generated.lua from *.weights.json.
 * Used by Compare.lua for sub-60 armor/jewelry/trinket ordering only.
 * Level 60 guide rows and level 70 curated lists keep hardcoded order.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const genDir = path.join(root, "GearQuest", "_generated");

const DEFAULT_SPEC = {
  WARRIOR: "arms",
  PALADIN: "retribution",
  HUNTER: "beast_mastery",
  ROGUE: "combat",
  PRIEST: "shadow",
  SHAMAN: "elemental",
  MAGE: "frost",
  WARLOCK: "affliction",
  DRUID: "feral",
};

/** Rogue weights JSON is not in repo yet; embed from pipeline notes / Wowhead melee prio. */
const EMBEDDED_CLASS_WEIGHTS = {
  ROGUE: {
    levelling_1_9: {
      agi: 1.0,
      str: 0.05,
      int: 0.05,
      sta: 0.35,
      spi: 0.02,
      ap: 0.12,
      rap: 0,
      feralAp: 0,
    },
    combat: {
      agi: 1.0,
      str: 0.05,
      int: 0.05,
      sta: 0.1,
      spi: 0.02,
      ap: 0.35,
      rap: 0,
      feralAp: 0,
      hit: 2.0,
      crit: 0.85,
      haste: 0.65,
      expertise: 0.1,
      armorPen: 0.1,
    },
    assassination: {
      agi: 1.0,
      str: 0.05,
      int: 0.05,
      sta: 0.1,
      spi: 0.02,
      ap: 0.35,
      rap: 0,
      feralAp: 0,
    },
    subtlety: {
      agi: 1.0,
      str: 0.05,
      int: 0.05,
      sta: 0.1,
      spi: 0.02,
      ap: 0.35,
      rap: 0,
      feralAp: 0,
    },
  },
};

const STAT_KEYS = [
  "agi",
  "str",
  "int",
  "sta",
  "spi",
  "ap",
  "rap",
  "feralAp",
  "heal",
  "sp",
  "hit",
  "crit",
  "haste",
  "expertise",
  "armorPen",
  "spellHit",
  "spellCrit",
  "spellHaste",
];

function pickStats(weights) {
  const out = {};
  for (const key of STAT_KEYS) {
    const val = weights[key];
    if (typeof val === "number") {
      out[key] = val;
    }
  }
  return out;
}

function luaNumber(n) {
  if (Number.isInteger(n)) return String(n);
  return String(n).replace(/(\.\d*?)0+$/, "$1").replace(/\.$/, "");
}

function luaTable(obj, indent) {
  const pad = "    ".repeat(indent);
  const lines = ["{"];
  for (const [k, v] of Object.entries(obj)) {
    lines.push(`${pad}    ${k} = ${luaNumber(v)},`);
  }
  lines.push(`${pad}}`);
  return lines.join("\n");
}

const classes = {};
const armorClasses = {};

for (const file of fs.readdirSync(genDir)) {
  const m = file.match(/^([A-Z]+)\.weights\.json$/);
  if (!m) continue;

  const classFile = m[1];
  const data = JSON.parse(fs.readFileSync(path.join(genDir, file), "utf8"));
  const block = data[classFile];
  if (!block) continue;

  classes[classFile] = {};
  armorClasses[classFile] = {};

  for (const [specId, specData] of Object.entries(block)) {
    if (specId.startsWith("_") || !specData.weights) continue;
    classes[classFile][specId] = pickStats(specData.weights);
    if (specData.armorClass) {
      armorClasses[classFile][specId] = specData.armorClass;
    }
  }

  const defaultSpec = DEFAULT_SPEC[classFile];
  if (defaultSpec && classes[classFile][defaultSpec]) {
    classes[classFile].default = { ...classes[classFile][defaultSpec] };
  }
  if (defaultSpec && armorClasses[classFile][defaultSpec]) {
    armorClasses[classFile].default = { ...armorClasses[classFile][defaultSpec] };
  }
}

for (const [classFile, specs] of Object.entries(EMBEDDED_CLASS_WEIGHTS)) {
  if (!classes[classFile]) {
    classes[classFile] = specs;
    if (DEFAULT_SPEC[classFile] && specs[DEFAULT_SPEC[classFile]]) {
      classes[classFile].default = { ...specs[DEFAULT_SPEC[classFile]] };
    }
  }
}

let out = `-- AUTO-GENERATED by scripts/generate-stat-weights-lua.mjs — do not edit.
-- Source: GearQuest/_generated/*.weights.json (TBC stat priority / pipeline weights).
-- Used for sub-60 BiS reordering in Compare.lua only.

local _, GQ = ...
GQ.StatWeights = GQ.StatWeights or {}

`;

for (const classFile of Object.keys(classes).sort()) {
  out += `GQ.StatWeights.${classFile} = {\n`;
  const specs = classes[classFile];
  const order = [
    "levelling_1_9",
    "default",
    ...Object.keys(specs).filter((k) => k !== "levelling_1_9" && k !== "default").sort(),
  ];
  const seen = new Set();
  for (const specId of order) {
    if (!specs[specId] || seen.has(specId)) continue;
    seen.add(specId);
    out += `    ${specId} = ${luaTable(specs[specId], 1)},\n`;
  }
  out += `}\n\n`;
}

out += `GQ.StatWeightsArmorClass = GQ.StatWeightsArmorClass or {}\n\n`;

for (const classFile of Object.keys(armorClasses).sort()) {
  const specs = armorClasses[classFile];
  if (Object.keys(specs).length === 0) continue;
  out += `GQ.StatWeightsArmorClass.${classFile} = {\n`;
  const order = [
    "levelling_1_9",
    "default",
    ...Object.keys(specs).filter((k) => k !== "levelling_1_9" && k !== "default").sort(),
  ];
  const seen = new Set();
  for (const specId of order) {
    if (!specs[specId] || seen.has(specId)) continue;
    seen.add(specId);
    out += `    ${specId} = ${luaTable(specs[specId], 1)},\n`;
  }
  out += `}\n\n`;
}

const outPath = path.join(genDir, "StatWeights.generated.lua");
fs.writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${Object.keys(classes).length} classes)`);
