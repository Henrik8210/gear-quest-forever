#!/usr/bin/env python3
"""Write GearQuest/Locales/Zones.lua: English zone name -> client area or map id.

Every zone/map string the addon data uses gets an id so the client can name it
in its own language (C_Map.GetAreaInfo / C_Map.GetMapInfo). Rerun after the
pipeline adds zones.

Usage: build-locale-zones.py <Questie>/Localization/lookups/lookupZones.lua [lookupZonesCorrections.lua]
(any recent Questie; an installed copy works)
"""

from __future__ import annotations

import collections
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ADDON = ROOT / "GearQuest"
OUT = ADDON / "Locales" / "Zones.lua"

# Zones whose uiMapId the data already carries (map=..., mapId=...) use it,
# stored negative. These add continents and zones with no area row.
MAP_IDS = {
    "Eastern Kingdoms": 1415,
    "Kalimdor": 1414,
    "Outland": 1945,
    "Riverglades": 2548,
    # The pin is the door on the parent map. The client has no separate map
    # under these names.
    "Hall of Thanes": 1455,
    "Excavation Site": 1437,
}


# Short names the addon uses for an area the client lists under a longer name.
ALIASES = {
    "Grom'gol": "Grom'gol Base Camp",
    "Theramore": "Theramore Isle",
}


def addon_zone_names() -> tuple[collections.Counter, dict[str, int]]:
    names: collections.Counter = collections.Counter()
    map_ids: dict[str, int] = {}
    files = list(ADDON.glob("*.lua")) + list((ADDON / "_generated").glob("*.lua"))
    for path in files:
        text = path.read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r'\b(?:zone|map|place)\s*=\s*"([^"]+)"', text):
            names[m.group(1)] += 1
        for m in re.finditer(r'map="([^"]+)",mapId=(\d+)', text):
            map_ids.setdefault(m.group(1), int(m.group(2)))
    return names, map_ids


def questie_area_ids(paths: list[str]) -> dict[str, list[int]]:
    ids: dict[str, set[int]] = collections.defaultdict(set)
    for p in paths:
        text = Path(p).read_text(encoding="utf-8")
        for m in re.finditer(r'\[(\d+)\]\s*=\s*"((?:[^"\\]|\\.)*)"', text):
            ids[m.group(2).replace("\\'", "'")].add(int(m.group(1)))
    return {k: sorted(v) for k, v in ids.items()}


def pick(candidates: list[int]) -> int | None:
    # Real area rows sit below 10000; Questie's synthetic ids start there.
    real = [i for i in candidates if 0 < i < 10000]
    if real:
        return real[0]
    return candidates[-1] if candidates and candidates[-1] >= 10000 else None


def main() -> None:
    area = questie_area_ids(sys.argv[1:])
    rows, missing = [], []
    names, data_map_ids = addon_zone_names()
    map_ids = {**data_map_ids, **MAP_IDS}
    for name in sorted(names):
        if name in map_ids:
            rows.append((name, -map_ids[name]))
            continue
        chosen = pick(area.get(ALIASES.get(name, name), []))
        if chosen is None:
            missing.append(name)
        else:
            rows.append((name, chosen))

    lines = [
        "local _, GQ = ...",
        "",
        "-- GENERATED by scripts/build-locale-zones.py. Do not edit by hand.",
        "-- English zone name -> AreaTable id (positive) or uiMapId (negative).",
        "-- The client names these in its own language. Zones missing here stay English.",
        "",
        "GQ.ZONE_IDS = {",
    ]
    for name, zid in rows:
        key = name.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'    ["{key}"] = {zid},')
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT}: {len(rows)} zones, missing: {', '.join(missing) or 'none'}")


if __name__ == "__main__":
    main()
